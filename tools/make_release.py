r"""Build customer deliverables for HKN Dentaire.

Usage:
    runtime\python.exe tools\make_release.py [--out PATH] [--name NAME] [--force]
                                             [--skip-setup] [--skip-smoke] [--write-lock]

Before building it checks that runtime/ matches backend/requirements.lock and
that the frontend build is newer than its sources; after building it installs
the kit into a temp folder (spaces, apostrophe, parentheses), runs init-prod, starts the
server and checks /api/health.

Produces in --out (default: repo parent):
    HKN_Dentaire_<date>.zip          portable kit (extractable, same content as payload)
    tools\HKN Dentaire Setup.exe     one-file installer (rebuilt by tools\build_native.py)

Both share file selection from hkn_packaging.py. No universal license is
shipped: the seller mints paste-in keys (tools\license.py mint) and hands one
to each clinic; keys are pasted during setup or at first launch.
"""
import argparse
import hashlib
import json
import os
import secrets
import shutil
import socket
import subprocess
import sys
import tempfile
import time
import urllib.request
import zipfile
from importlib import metadata
from datetime import UTC, datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from hkn_packaging import MANIFEST_NAME, select_files

REPO = Path(__file__).resolve().parent.parent
LOCK = REPO / "backend" / "requirements.lock"


# ------------------------------------------------------------ pre-flight ---
def runtime_packages() -> dict[str, str]:
    """{normalized name: version} of every distribution in the running runtime."""
    out = {}
    for dist in metadata.distributions():
        name = (dist.metadata["Name"] or "").strip().lower().replace("_", "-")
        if name:
            out[name] = dist.version
    return out


def write_lock() -> None:
    pkgs = runtime_packages()
    LOCK.write_text(
        "# Exact versions inside runtime/ (generated by tools/make_release.py --write-lock).\n"
        "# Rebuild runtime/ with: runtime\\python.exe -m pip install -r backend/requirements.lock\n"
        + "".join(f"{n}=={v}\n" for n, v in sorted(pkgs.items())),
        encoding="utf-8",
    )
    print(f"Lock written: {LOCK} ({len(pkgs)} packages)")


def check_lock() -> None:
    """The shipped runtime must match the committed lock exactly (reproducible builds)."""
    if not LOCK.is_file():
        raise SystemExit(f"{LOCK} manquant: lancez make_release.py --write-lock puis committez-le.")
    if Path(sys.executable).resolve().parent != (REPO / "runtime").resolve():
        raise SystemExit("Lancez make_release.py avec runtime\\python.exe (le runtime livre).")
    wanted = {}
    for line in LOCK.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if "==" in line:
            n, v = line.split("==", 1)
            wanted[n.strip().lower()] = v.strip()
    have = runtime_packages()
    diff = sorted(
        f"{n}: lock={wanted.get(n)} runtime={have.get(n)}"
        for n in set(wanted) | set(have)
        if wanted.get(n) != have.get(n)
    )
    if diff:
        raise SystemExit("runtime/ ne correspond pas a requirements.lock:\n  " + "\n  ".join(diff))
    print(f"Runtime matches lock ({len(have)} packages).")


def check_frontend_fresh() -> None:
    """Refuse to ship a frontend build older than its sources."""
    index = REPO / "frontend" / ".output" / "public" / "index.html"
    if not index.is_file():
        raise SystemExit("Frontend non construit: cd frontend && npm run generate")
    built = index.stat().st_mtime
    sources = [REPO / "frontend" / "nuxt.config.ts", REPO / "frontend" / "package.json"]
    sources += [p for p in (REPO / "frontend" / "app").rglob("*") if p.is_file()]
    newer = [p for p in sources if p.is_file() and p.stat().st_mtime > built + 1]
    if newer:
        raise SystemExit(
            "Le build frontend est plus ancien que ses sources (ex: "
            + str(newer[0].relative_to(REPO)) + "). Lancez: cd frontend && npm run generate"
        )
    print("Frontend build is up to date.")


# ------------------------------------------------------------ smoke test ---
def _free_port() -> int:
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


def _health(port: int) -> dict | None:
    try:
        with urllib.request.urlopen(f"http://127.0.0.1:{port}/api/health", timeout=2) as r:
            return json.loads(r.read().decode("utf-8")) if r.status == 200 else None
    except Exception:
        return None


def smoke_test(zip_path: Path) -> None:
    """Install the kit like a clinic would and check the server comes up.

    Extracts to a temp path containing spaces, an apostrophe and parentheses (worst case
    for initdb/pg_ctl), runs init-prod, starts the launcher on a free port,
    checks /api/health, then stops everything and deletes the folder.
    """
    base = Path(tempfile.mkdtemp(prefix="HKN smoke d'essai (1) "))
    launcher = None
    log = None
    root = base / "Dental care software"
    py = root / "runtime" / "python.exe"
    env = {k: v for k, v in os.environ.items() if not k.startswith("CLINIC_")}
    env["PYTHONIOENCODING"] = "utf-8"
    passed = False

    def pg_log_tail() -> str:
        pg_log = root / "data" / "pgdata" / "log"
        if pg_log.is_file():
            return "\n--- PostgreSQL log ---\n" + pg_log.read_text(encoding="utf-8", errors="replace")[-2000:]
        return ""

    try:
        print(f"Smoke test in: {base}")
        with zipfile.ZipFile(zip_path) as zf:
            zf.extractall(base)
        port = _free_port()
        (root / "data").mkdir(parents=True, exist_ok=True)
        (root / "data" / "config.json").write_text(json.dumps({"port": port, "lan": False}), encoding="utf-8")

        t0 = time.time()
        init_env = dict(env)
        init_env.update({
            "CLINIC_INIT_USERNAME": "smoketest",
            "CLINIC_INIT_PASSWORD": "Sm0ke!" + secrets.token_hex(6),
            "CLINIC_INIT_FULLNAME": "Smoke Test",
        })
        proc = subprocess.run(
            [str(py), str(root / "backend" / "app" / "cli.py"), "init-prod"],
            cwd=root, env=init_env, capture_output=True, text=True, encoding="utf-8",
            errors="replace", timeout=600,
        )
        if proc.returncode != 0:
            raise SystemExit(
                "SMOKE: init-prod a echoue:\n" + proc.stdout[-1500:] + proc.stderr[-1500:] + pg_log_tail()
            )
        print(f"  init-prod OK ({time.time() - t0:.0f}s)")

        log = open(base / "launcher.log", "w", encoding="utf-8", errors="replace")
        launcher = subprocess.Popen(
            [str(py), str(root / "backend" / "app" / "launcher.py"), "--no-browser"],
            cwd=root, env=env, stdout=log, stderr=subprocess.STDOUT,
        )
        deadline = time.time() + 180
        health = None
        while time.time() < deadline and launcher.poll() is None:
            health = _health(port)
            if health:
                break
            time.sleep(1)
        if not health or not health.get("database"):
            log.flush()
            tail = (base / "launcher.log").read_text(encoding="utf-8", errors="replace")[-3000:]
            raise SystemExit(f"SMOKE: le serveur n'a pas demarre (health={health}).\n{tail}{pg_log_tail()}")
        print(f"  server healthy on port {port} ({time.time() - t0:.0f}s total)")
        passed = True
    finally:
        if launcher is not None and launcher.poll() is None:
            launcher.terminate()
            try:
                launcher.wait(timeout=20)
            except subprocess.TimeoutExpired:
                launcher.kill()
        if log is not None:
            log.close()
        if py.is_file():
            subprocess.run([str(py), str(root / "backend" / "app" / "cli.py"), "stop-server"],
                           cwd=root, env=env, capture_output=True, timeout=120)
        time.sleep(1)
        if passed:
            shutil.rmtree(base, ignore_errors=True)
        else:
            print(f"SMOKE: dossier conserve pour analyse: {base}")
    print("Smoke test passed.")


def _sha256(p: Path) -> str:
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def build_setup() -> None:
    proc = subprocess.run(
        [sys.executable, str(REPO / "tools" / "build_native.py")],
        check=False,
        capture_output=True,
        text=True,
        cwd=str(REPO),
    )
    sys.stdout.write(proc.stdout)
    sys.stderr.write(proc.stderr)
    if proc.returncode != 0:
        raise SystemExit(f"tools/build_native.py failed (code {proc.returncode})")


def build_zip(out_dir: Path, name: str, force: bool) -> Path:
    items = select_files(REPO)

    required = (
        "runtime/python.exe",
        "frontend/.output/public/index.html",
        "scripts/HKN Dentaire.exe",
        "scripts/start.bat",
        "scripts/stop.bat",
        "scripts/install.bat",
        "scripts/read_password.ps1",
        "backend/app/main.py",
        "backend/migrations/env.py",
        "branding/app.ico",
        "VERSION",
    )
    rels = {rel for rel, _ in items}
    missing = [r for r in required if r not in rels]
    if missing:
        raise SystemExit("MANQUANT dans le paquet: " + ", ".join(missing))

    # cmd.exe / wscript misparse LF-only scripts (lost first characters of
    # lines, broken labels): every shipped Windows script must be CRLF.
    lf_scripts = [
        rel for rel, p in items
        if rel.lower().endswith((".bat", ".cmd", ".vbs", ".ps1"))
        and b"\n" in (data := p.read_bytes()) and data.count(b"\n") != data.count(b"\r\n")
    ]
    if lf_scripts:
        raise SystemExit("Scripts avec fins de ligne LF (convertir en CRLF): " + ", ".join(lf_scripts))

    banned = [rel for rel, _ in items if rel.startswith("data/") or rel.endswith("/private.pem")]
    if banned:
        raise SystemExit("SAFETY ABORT: fichiers interdits: " + ", ".join(banned))

    stamp = datetime.now(UTC).strftime("%Y%m%d")
    if "%Y" in name:
        name = name.replace("%Y", stamp)
    zip_path = out_dir / (name + ".zip")
    if zip_path.exists():
        if not force:
            raise SystemExit("refuse d'écraser " + str(zip_path) + " (utilisez --force)")
        zip_path.unlink()

    # MANIFEST.txt is already the last item (hkn_packaging.select_files), so the
    # zip kit and the Setup payload carry the same install manifest.
    if MANIFEST_NAME not in rels:
        raise SystemExit("MANQUANT dans le paquet: " + MANIFEST_NAME)
    root = "Dental care software"
    entries = []
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as zf:
        for rel, p in items:
            arc = root + "/" + rel
            zf.write(p, arc)
            entries.append((rel, arc, p))

    size_mb = zip_path.stat().st_size / (1024 * 1024)
    digest = _sha256(zip_path)
    print(f"ZIP: {zip_path} ({len(entries)} files, {size_mb:.1f} MB)")
    print(f"SHA256 zip: {digest}")
    return zip_path

def main() -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("--name", default="HKN_Dentaire_%Y", help="nom de base du zip (%%Y = date)")
    parser.add_argument("--out", default=None, help="dossier de sortie (défaut: parent du dépôt)")
    parser.add_argument("--force", action="store_true", help="écraser le zip existant")
    parser.add_argument("--skip-setup", action="store_true", help="ne pas reconstruire le Setup.exe")
    parser.add_argument("--skip-smoke", action="store_true", help="ne pas lancer le test d'installation")
    parser.add_argument("--write-lock", action="store_true", help="regenerer backend/requirements.lock et quitter")
    args = parser.parse_args()
    # Paths may contain non-ASCII letters: never crash on a cp1252 console.
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(errors="replace")
        except (AttributeError, ValueError):
            pass

    if args.write_lock:
        write_lock()
        return 0

    check_lock()
    check_frontend_fresh()
    if not args.skip_setup:
        build_setup()

    out_dir = Path(args.out) if args.out else REPO.parent
    out_dir.mkdir(parents=True, exist_ok=True)
    zip_path = build_zip(out_dir, args.name, args.force)
    if not args.skip_smoke:
        smoke_test(zip_path)

    setup = REPO / "tools" / "HKN Dentaire Setup.exe"
    if setup.exists():
        print(f"SHA256 setup: {_sha256(setup)}")
    print(f"OK: {zip_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
